import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'packages/design-tokens/tokens.json'), 'utf8'));
const kebab = value => value.replace(/[A-Z]/g, x => '-' + x.toLowerCase());
const stack = (names, fallback) => names.map(n => n.startsWith('-') || n === 'BlinkMacSystemFont' ? n : JSON.stringify(n)).concat(fallback).join(', ');
const css = ['/* Generated by scripts/sync-typography.mjs from design-tokens/tokens.json. */', ':root {',
  ...Object.entries(tokens.font).map(([key, value]) => `  --font-${key}: ${stack(value, key === 'sans' ? 'sans-serif' : key === 'mono' ? 'monospace' : 'serif')};`),
  ...Object.entries(tokens.typography).flatMap(([group, values]) => Object.entries(values).map(([key, value]) => `  --type-${group}-${kebab(key)}: ${value}${group === 'size' ? 'px' : ''};`)), '}',''].join('\n');
const targets = ['packages/design-tokens/typography.css', 'apps/web-h5/src/theme/typography-tokens.css'];
let drift = false;
for (const target of targets) {
  // H5 is a separate repository and may not be checked out with the admin sources.
  if (target.startsWith('apps/web-h5') && !existsSync(resolve(root, 'apps/web-h5/src'))) continue;
  const path = resolve(root, target);
  if (process.argv.includes('--check')) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== css) { console.error('Typography drift: ' + target); drift = true; }
  } else { writeFileSync(path, css); console.log('Generated ' + target); }
}
// Keep native role sizes aligned without overwriting platform font resolution code.
for (const target of ['apps/ios-customer/DongFangApp/DesignSystem/Tokens.swift', 'apps/ios-master/MasterApp/DesignSystem/Tokens.swift']) {
  const path = resolve(root, target);
  const original = readFileSync(path, 'utf8');
  let updated = original;
  for (const [role, key] of Object.entries({navigation:'nav', hero:'hero', page:'page', section:'section', card:'card'})) {
    updated = updated.replace(new RegExp(`static let ${role} = title\\(\\d+\\)`), `static let ${role} = title(${tokens.typography.size[key]})`);
  }
  if (process.argv.includes('--check')) {
    if (updated !== original) { console.error('Typography drift: ' + target); drift = true; }
  } else if (updated !== original) writeFileSync(path, updated);
}
if (drift) process.exit(1);
